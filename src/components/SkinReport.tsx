interface ScanData {
  overall_score: number;
  skin_age_estimate: number;
  hydration_score: number;
  texture_score: number;
  pigmentation_score: number;
  inflammation_score: number;
  elasticity_score: number;
  summary_text: string;
  created_at: string;
}

interface SkinReportProps {
  scan: ScanData;
  userName: string;
}

export default function SkinReport({ scan, userName }: SkinReportProps) {
  const handlePrint = () => {
    const printWindow = window.open('', '_blank');
    if (!printWindow) return;

    const date = new Date(scan.created_at).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
    const metrics = [
      { label: 'Hydration', score: scan.hydration_score },
      { label: 'Texture', score: scan.texture_score },
      { label: 'Pigmentation', score: scan.pigmentation_score },
      { label: 'Inflammation', score: scan.inflammation_score },
      { label: 'Elasticity', score: scan.elasticity_score },
    ];

    const html = `<!DOCTYPE html>
<html>
<head>
<title>SkinPulse Report — ${date}</title>
<style>
  * { margin:0; padding:0; box-sizing:border-box; }
  body { font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif; color:#2a2a2a; padding:48px; max-width:700px; margin:0 auto; }
  .brand { color:#6ba3a0; font-weight:700; font-size:20px; margin-bottom:4px; }
  .date { color:#999; font-size:13px; margin-bottom:32px; }
  .name { font-size:16px; color:#555; margin-bottom:8px; }
  .score-block { text-align:center; padding:32px 0; margin-bottom:32px; border-bottom:1px solid #eee; }
  .score-num { font-size:72px; font-weight:700; color:#6ba3a0; }
  .score-label { font-size:14px; color:#888; }
  .age-block { text-align:center; margin-bottom:32px; padding-bottom:24px; border-bottom:1px solid #eee; }
  .age-num { font-size:36px; font-weight:600; }
  .metrics { display:grid; grid-template-columns:1fr 1fr; gap:16px; margin-bottom:32px; }
  .metric { padding:16px; border-radius:12px; background:#f8f6f3; }
  .metric-label { font-size:13px; color:#888; }
  .metric-score { font-size:28px; font-weight:600; }
  .bar { height:6px; border-radius:3px; background:#eee; margin-top:8px; }
  .bar-fill { height:6px; border-radius:3px; background:#6ba3a0; }
  .summary { padding:24px; border-radius:12px; background:#f8f6f3; font-size:14px; line-height:1.7; color:#555; margin-bottom:24px; }
  .disclaimer { font-size:11px; color:#aaa; text-align:center; margin-top:32px; }
  @media print { body { padding:24px; } }
</style>
</head>
<body>
  <div class="brand">SkinPulse</div>
  <div class="name">${userName}</div>
  <div class="date">${date}</div>

  <div class="score-block">
    <div class="score-num">${scan.overall_score}</div>
    <div class="score-label">Skin Health Score</div>
  </div>

  <div class="age-block">
    <div class="age-num">${scan.skin_age_estimate} years</div>
    <div class="score-label">Estimated Skin Age</div>
  </div>

  <div class="metrics">
    ${metrics.map(m => `
      <div class="metric">
        <div class="metric-label">${m.label}</div>
        <div class="metric-score">${m.score}</div>
        <div class="bar"><div class="bar-fill" style="width:${m.score}%"></div></div>
      </div>
    `).join('')}
  </div>

  <div class="summary">
    <strong>Summary Insights</strong><br/><br/>
    ${scan.summary_text}
  </div>

  <div class="disclaimer">
    This report provides general wellness insights only and is not a medical diagnosis.<br/>
    Generated by SkinPulse on ${date}.
  </div>
</body>
</html>`;

    printWindow.document.write(html);
    printWindow.document.close();
    printWindow.onload = () => printWindow.print();
  };

  return (
    <button onClick={handlePrint} className="btn-secondary text-sm">
      📄 Download Report
    </button>
  );
}
